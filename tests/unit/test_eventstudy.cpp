// P-QE acceptance test for the two heterogeneity-robust event-study estimators:
//
//   sunab_run      — Sun & Abraham (2021) interaction-weighted event study
//   didimpute_run  — Borusyak, Jaravel & Spiess (2024) imputation estimator
//
// The oracle is real Stata 19.5 output on the pangram wave fixture
// (internal fixture wave_fixture.dta), for
//
//   eventstudyinteract y F2 F3 F4 L2 L3 L4, absorb(id t) cohort(cohort) ///
//       control_cohort(never_treat) vce(cluster id)
//   did_imputation y id t cohort, horizons(0/3) pretrends(2) autosample
//
// The fixture is generated by a closed-form deterministic do-file
// (waves/_shared/fixture_stata.do) with no RNG anywhere, so this test
// REGENERATES it arithmetically instead of reading the .dta — the numbers below
// are then a self-contained pin that cannot silently drift with a missing or
// re-exported fixture file. The regeneration was verified against Stata's own
// exported values: max |dy| = 2.7e-15 across all 4800 rows.
//
// Every assertion is "consistent with the PRINTED oracle at 1e-6 relative": the
// tolerance is half a unit in the last printed place plus 1e-6 of the target,
// so a value Stata printed to 5 significant digits is not held to 7.
//
// ---------------------------------------------------------------------------
// Candidate sweeps behind two conventions the papers leave open (fleet law
// BUG-164/BUG-175 — never ship the first plausible formula when several exist):
//
//   IW WEIGHT NORMALIZATION (sunab). Three denominators were implemented and
//   measured against the six oracle coefficients:
//     (a) cohort share of the ESTIMATION-SAMPLE observations at relative
//         period l                                    -> max rel err 1.3e-07  <-- oracle
//     (b) same share over ALL data rows, including those a missing outcome
//         drops                                       -> max rel err 1.4e-03
//     (c) unit-level cohort shares (relative-period-independent)
//                                                     -> max rel err 1.4e-03
//   (b) and (c) coincide here and both miss in the third decimal.
//
//   TREATED-CELL RESIDUAL (didimpute). The variance needs an eps for the
//   imputed cells; measured against the four oracle tau standard errors:
//     (a) deviation from the cell's own (cohort, horizon) mean
//                                                     -> max rel err 4.7e-07  <-- oracle
//     (b) deviation from the pooled horizon mean tau_h -> max rel err 1.5e-04
//     (c) raw imputed effect, uncentred                -> max rel err 5.4e-01
//     (d) leave-one-out inflation of (b)               -> max rel err 4.8e-03

#include <cmath>
#include <cstdio>
#include <string>
#include <vector>

#include "estimators/didimpute.h"
#include "estimators/sunab.h"

using namespace cecon;

static int g_fail = 0;

// tol = half a unit in the last printed place + 1e-6 relative.
static void chk(const char* what, double got, double want, int decimals) {
    const double tol = 0.5 * std::pow(10.0, -decimals) + 1e-6 * std::fabs(want);
    if (!(std::fabs(got - want) <= tol)) {
        std::printf("  FAIL %-28s got %.10g  want %.10g  (tol %.3g)\n", what, got, want, tol);
        ++g_fail;
    } else {
        std::printf("  ok   %-28s %.10g\n", what, got);
    }
}

static void chk_i(const char* what, long long got, long long want) {
    if (got != want) {
        std::printf("  FAIL %-28s got %lld  want %lld\n", what, got, want);
        ++g_fail;
    } else {
        std::printf("  ok   %-28s %lld\n", what, got);
    }
}

static void chk_s(const char* what, const std::string& got, const std::string& want) {
    if (got != want) {
        std::printf("  FAIL %-28s\n        got  \"%s\"\n        want \"%s\"\n", what,
                    got.c_str(), want.c_str());
        ++g_fail;
    } else {
        std::printf("  ok   %-28s \"%s\"\n", what, got.c_str());
    }
}

// ---------------------------------------------------------------------------
// The pangram wave fixture, regenerated from waves/_shared/fixture_stata.do.
struct Fixture {
    std::vector<double> y, id, t, cohort, never;
    std::vector<double> F2, F3, F4, L2, L3, L4;
    int64_t n = 0;
};

static Fixture make_fixture() {
    Fixture f;
    for (long long nn = 1; nn <= 4800; ++nn) {
        const double dn = static_cast<double>(nn);
        const double id = std::ceil(dn / 24.0);
        const double t = static_cast<double>((nn - 1) % 24 + 1);
        const double x1 = std::sin(dn / 7.0) + id / 200.0;
        const double x2 = std::cos(dn / 11.0) + t / 30.0;
        const double cohort = id <= 160 ? 9.0 + static_cast<double>(static_cast<long long>(id) % 6)
                                        : 0.0;
        const double treated = (cohort > 0 && t >= cohort) ? 1.0 : 0.0;
        const double running = static_cast<double>((nn - 1) % 101 - 50) / 10.0;
        const double rd = running >= 0 ? 1.0 : 0.0;
        const double y = 2.0 + 0.8 * x1 - 0.4 * x2 + 1.2 * treated + 0.3 * rd + id / 1000.0 +
                         t / 100.0 + std::sin(dn / 5.0);
        if (nn % 211 == 0) continue;  // y is extended-missing (.a) on these rows
        f.y.push_back(y);
        f.id.push_back(id);
        f.t.push_back(t);
        f.cohort.push_back(cohort);
        f.never.push_back(cohort == 0 ? 1.0 : 0.0);
        const double rel = t - cohort;
        auto ind = [&](double k) { return (cohort > 0 && rel == k) ? 1.0 : 0.0; };
        f.F2.push_back(ind(-2)); f.F3.push_back(ind(-3)); f.F4.push_back(ind(-4));
        f.L2.push_back(ind(2));  f.L3.push_back(ind(3));  f.L4.push_back(ind(4));
    }
    f.n = static_cast<int64_t>(f.y.size());
    return f;
}

// ---------------------------------------------------------------------------
static void test_sunab(const Fixture& f) {
    std::printf("eventstudyinteract (Sun-Abraham IW):\n");
    const int L = 6;
    std::vector<double> rel(static_cast<size_t>(f.n) * L);
    const std::vector<const std::vector<double>*> cols{&f.F2, &f.F3, &f.F4,
                                                       &f.L2, &f.L3, &f.L4};
    for (int l = 0; l < L; ++l)
        for (int64_t i = 0; i < f.n; ++i)
            rel[static_cast<size_t>(l) * f.n + i] = (*cols[static_cast<size_t>(l)])[static_cast<size_t>(i)];

    SunabResult R = sunab_run(f.y.data(), rel.data(), L, f.cohort.data(), f.never.data(),
                              f.id.data(), f.t.data(), f.id.data(), f.n);
    if (!R.ok) {
        std::printf("  FAIL sunab_run: %s\n", R.error.c_str());
        ++g_fail;
        return;
    }
    chk_i("N", R.n_obs, 4778);
    chk_i("weight-sample obs", R.n_obs_weights, 3822);
    chk_i("clusters", R.n_clusters, 200);
    chk_i("F df1", R.df1, 36);
    chk_i("F df2", R.df2, 199);
    chk("F", R.F, 359.31, 2);
    chk("R-squared", R.r2, 0.3572, 4);
    chk("Adj R-squared", R.r2_a, 0.3205, 4);
    chk("Root MSE", R.rmse, 0.9168, 4);

    // name, coef, dp(coef), se, dp(se), t, ci_lo, dp(lo), ci_hi, dp(hi)
    struct Row { const char* nm; double b; int bd; double se; int sd; double t;
                 double lo; int ld; double hi; int hd; };
    const Row want[] = {
        {"F2", -.5555558, 7, .050379,  6, -11.03, -.6549009, 7, -.4562107, 7},
        {"F3", -.4803082, 7, .0548886, 7,  -8.75, -.5885462, 7, -.3720702, 7},
        {"F4", -.369623,  6, .0572178, 7,  -6.46, -.482454,  6, -.256792,  6},
        {"L2",  .3032057, 7, .0487119, 7,   6.22,  .2071479, 7,  .3992635, 7},
        {"L3",  .2639315, 7, .0516402, 7,   5.11,  .1620992, 7,  .3657638, 7},
        {"L4",  .2156004, 7, .0524298, 7,   4.11,  .1122111, 7,  .3189897, 7},
    };
    chk_i("rows", static_cast<long long>(R.coefs.size()), 6);
    for (int l = 0; l < 6 && l < static_cast<int>(R.coefs.size()); ++l) {
        const auto& c = R.coefs[static_cast<size_t>(l)];
        const Row& w = want[l];
        chk((std::string(w.nm) + " coef").c_str(), c.coef, w.b, w.bd);
        chk((std::string(w.nm) + " se").c_str(), c.se, w.se, w.sd);
        chk((std::string(w.nm) + " t").c_str(), c.t, w.t, 2);
        chk((std::string(w.nm) + " ci_lo").c_str(), c.ci_lo, w.lo, w.ld);
        chk((std::string(w.nm) + " ci_hi").c_str(), c.ci_hi, w.hi, w.hd);
        // The IW weights are a probability distribution over the six cohorts.
        double s = 0;
        for (double x : c.cohort_weight) s += x;
        chk((std::string(w.nm) + " weights sum").c_str(), s, 1.0, 12);
    }
    chk_i("cohorts interacted", static_cast<long long>(R.cohorts.size()), 6);

    // vce(cluster) is the only shape implemented — a null cluster is refused,
    // not silently downgraded to iid.
    SunabResult bad = sunab_run(f.y.data(), rel.data(), L, f.cohort.data(), f.never.data(),
                                f.id.data(), f.t.data(), /*cluster=*/nullptr, f.n);
    if (bad.ok || bad.error.find("cluster") == std::string::npos) {
        std::printf("  FAIL missing cluster was not refused by name\n");
        ++g_fail;
    } else {
        std::printf("  ok   %-28s \"%s\"\n", "no-cluster refused", bad.error.c_str());
    }
}

// ---------------------------------------------------------------------------
static void test_didimpute(const Fixture& f) {
    std::printf("did_imputation (Borusyak-Jaravel-Spiess):\n");
    DidImputeConfig cfg;
    cfg.horizons = {0, 1, 2, 3};
    cfg.pretrends = 2;
    cfg.autosample = true;
    // cohort == 0 for the never-treated units of this fixture. Zero precedes the
    // first observed period, so those units are treated in EVERY period and have
    // no untreated observation to identify their unit effect — which is exactly
    // the sample autosample() drops, and exactly what the oracle's warning names.
    DidImputeResult R = didimpute_run(f.y.data(), f.id.data(), f.t.data(), f.cohort.data(),
                                      f.n, cfg);
    if (!R.ok) {
        std::printf("  FAIL didimpute_run: %s\n", R.error.c_str());
        ++g_fail;
        return;
    }
    chk_i("N", R.n_obs, 2044);
    chk_i("Y(0) model rows", R.n_model, 1672);
    chk_s("autosample warning", R.autosample_message,
          "Warning: part of the sample was dropped for the following coefficients "
          "because FE could not be imputed: tau0 tau1 tau2 tau3.");

    struct Row { const char* nm; double b; int bd; double se; int sd; double z;
                 double lo; int ld; double hi; int hd; };
    const Row want[] = {
        {"tau0", 1.208196, 6, .0886614, 7, 13.63, 1.034423, 6, 1.381969, 6},
        {"tau1", 1.200517, 6, .1298647, 7,  9.24,  .9459869, 7, 1.455047, 6},
        {"tau2", 1.195442, 6, .1758188, 7,  6.80,  .8508435, 7, 1.540041, 6},
        {"tau3", 1.209136, 6, .2227719, 7,  5.43,  .7725111, 7, 1.645761, 6},
        {"pre1",  .024978, 6, .1130598, 7,  0.22, -.1966152, 7,  .2465712, 7},
        {"pre2",  .0029765,7, .0663103, 7,  0.04, -.1269894, 7,  .1329424, 7},
    };
    chk_i("rows", static_cast<long long>(R.coefs.size()), 6);
    for (size_t j = 0; j < R.coefs.size() && j < 6; ++j) {
        const auto& c = R.coefs[j];
        const Row& w = want[j];
        chk_s((std::string("row ") + std::to_string(j) + " name").c_str(), c.name, w.nm);
        chk((std::string(w.nm) + " coef").c_str(), c.estimate, w.b, w.bd);
        chk((std::string(w.nm) + " se").c_str(), c.se, w.se, w.sd);
        chk((std::string(w.nm) + " z").c_str(), c.z, w.z, 2);
        chk((std::string(w.nm) + " ci_lo").c_str(), c.ci_lo, w.lo, w.ld);
        chk((std::string(w.nm) + " ci_hi").c_str(), c.ci_hi, w.hi, w.hd);
    }
    // The pre-trend cells stay INSIDE the Y(0) estimation sample, so they lose
    // no observations — only the four tau rows do.
    chk_i("coefs that lost sample", static_cast<long long>(R.autosample_coefs.size()), 4);

    // Without autosample the unimputable cells are an error, not a silent drop.
    cfg.autosample = false;
    DidImputeResult noauto = didimpute_run(f.y.data(), f.id.data(), f.t.data(),
                                           f.cohort.data(), f.n, cfg);
    if (noauto.ok || noauto.error.find("autosample") == std::string::npos) {
        std::printf("  FAIL unimputable cells were not refused without autosample\n");
        ++g_fail;
    } else {
        std::printf("  ok   %-28s \"%s\"\n", "no-autosample refused", noauto.error.c_str());
    }

    // A never-treated unit spelled the OTHER way (missing first-treated period)
    // keeps its rows in the Y(0) model, so nothing is dropped at all.
    std::vector<double> gmiss = f.cohort;
    for (auto& g : gmiss) if (g == 0) g = std::nan("");
    cfg.autosample = true;
    DidImputeResult R2 = didimpute_run(f.y.data(), f.id.data(), f.t.data(), gmiss.data(),
                                       f.n, cfg);
    if (!R2.ok || R2.autosample_dropped) {
        std::printf("  FAIL missing-gvar never-treated encoding still dropped sample\n");
        ++g_fail;
    } else {
        // 160 treated units x their pre-treatment periods (1680) + 40 never-treated
        // units x 24 periods (960), less the 12 missing-outcome rows among them.
        chk_i("never-treated encoding rows", R2.n_model, 2628);
    }
}

int test_eventstudy_main() {
    std::printf("test_eventstudy:\n");
    const Fixture f = make_fixture();
    chk_i("fixture rows", f.n, 4778);
    test_sunab(f);
    test_didimpute(f);
    if (g_fail) {
        std::printf("FAILED (%d checks)\n", g_fail);
        return 1;
    }
    std::printf("PASSED\n");
    return 0;
}
