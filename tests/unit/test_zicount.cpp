// P7 wave — zip / zinb / fracreg oracle assertions (Stata 19.5,
// internal capture p7_stata.log). Tolerances follow the
// wave rule — coefficients rtol 1e-6, standard errors rtol 1e-5, log-likelihood
// rtol 1e-6.
//
// The sample is the wave fixture (_artifacts/wave_fixture.dta, 4,800 rows) with
// the count variable built exactly as internal script p7.do:4-5
// does it:
//     generate int p7_count = ycount * (1 + mod(id,4))
//     replace  p7_count = 0 if mod(id+t,7)==0
// (the `replace` is unconditional on the current value, so it also un-missings a
// row whose ycount was missing — reproduced below, and it is part of why the
// estimation sample is 4,671 and not 4,678).
//
// EXCEPTION on fracreg's standard errors: this fixture's yfrac is EXACTLY the
// inverse logit of the model, so its robust SEs land at ~1e-12 — the size of the
// numerical noise itself. Those are asserted by MAGNITUDE only; asserting their
// digits would pin the compiler's FMA contraction, not the estimator.
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <string>
#include <vector>

#include "core/linalg.h"
#include "estimators/logit.h"
#include "estimators/zicount.h"
#include "io/dta_reader.h"
#include "validate_dir.h"

using namespace cecon;

static int fail = 0;

static void chk(const char* tag, double got, double want, double rtol) {
    double rel = std::fabs(got - want) / (std::fabs(want) + 1e-30);
    std::printf("  %-26s got=%-16.10g stata=%-14.10g rel=%.2e\n", tag, got, want, rel);
    if (!(rel <= rtol)) {
        std::printf("    <<FAIL %s rel %.2e > %.0e\n", tag, rel, rtol);
        fail = 1;
    }
}

static void chk_abs(const char* tag, double got, double want, double atol) {
    double d = std::fabs(got - want);
    std::printf("  %-26s got=%-16.12g stata=%-14.10g abs=%.2e\n", tag, got, want, d);
    if (!(d <= atol)) {
        std::printf("    <<FAIL %s abs %.2e > %.0e\n", tag, d, atol);
        fail = 1;
    }
}

static void want_true(const char* tag, bool cond) {
    std::printf("  %-26s %s\n", tag, cond ? "ok" : "FAIL");
    if (!cond) fail = 1;
}

// The wave fixture lives next to the pangram do-files, not in tests/validate/.
// COBRA_WAVE_DIR overrides; otherwise it is resolved relative to the validate
// directory (which CMake points at this source tree).
static std::string wave_fixture_path() {
    if (const char* env = std::getenv("COBRA_WAVE_DIR")) {
        if (*env) {
            std::string d = env;
            if (d.back() != '/') d += '/';
            return d + "wave_fixture.dta";
        }
    }
    return cobra_test::require_fixture(
        cobra_test::validate_dir() + "../kitchensink/pangram/waves/_artifacts/wave_fixture.dta",
        "wave_fixture.dta");
}

// V = factor * bread * meat * bread for a logit-family fit whose per-row score is
// e_i * x_i (fracreg's; e = y - p). Same shape cmds_mle.cpp's cmd_logit builds.
static std::vector<double> logit_robust_vcov(const std::vector<double>& X, int64_t n, int k,
                                             const std::vector<double>& e,
                                             const std::vector<double>& bread, double factor) {
    std::vector<double> meat(static_cast<size_t>(k) * k, 0.0);
    for (int64_t i = 0; i < n; ++i) {
        double e2 = e[static_cast<size_t>(i)] * e[static_cast<size_t>(i)];
        for (int c = 0; c < k; ++c) {
            double xc = X[static_cast<int64_t>(c) * n + i];
            for (int d = 0; d < k; ++d)
                meat[static_cast<size_t>(c) * k + d] += e2 * xc * X[static_cast<int64_t>(d) * n + i];
        }
    }
    std::vector<double> V(static_cast<size_t>(k) * k, 0.0), tmp(static_cast<size_t>(k) * k, 0.0);
    la::sandwich(bread.data(), meat.data(), k, factor, V.data(), tmp.data());
    return V;
}

int test_zicount_main() {
    std::printf("test_zicount:\n");
    const std::string path = wave_fixture_path();
    DtaResult dta;
    try {
        dta = read_dta(path);
    } catch (const std::exception& ex) {
        std::printf("  FAIL: cannot read the P7 wave fixture\n    %s\n    %s\n"
                    "    (generated by the User's Stata run; set COBRA_WAVE_DIR to the\n"
                    "     directory holding wave_fixture.dta)\n",
                    path.c_str(), ex.what());
        return 1;
    }
    const Frame& fr = dta.frame;
    const int64_t nraw = fr.n_rows();
    std::printf("  fixture rows=%lld cols=%d\n", (long long)nraw, fr.n_cols());
    if (nraw != 4800) { std::printf("  FAIL: expected 4,800 raw rows\n"); return 1; }
    for (const char* v : {"id", "t", "ycount", "x1", "x2", "yfrac"})
        if (!fr.has(v)) { std::printf("  FAIL: fixture has no column %s\n", v); return 1; }

    const auto& c_id = fr.col("id").f64;
    const auto& c_t = fr.col("t").f64;
    const auto& c_yc = fr.col("ycount").f64;
    const auto& c_x1 = fr.col("x1").f64;
    const auto& c_x2 = fr.col("x2").f64;
    const auto& c_yf = fr.col("yfrac").f64;

    // p7.do:4-5, verbatim.
    std::vector<double> cnt(static_cast<size_t>(nraw));
    int64_t n_replaced = 0;
    for (int64_t i = 0; i < nraw; ++i) {
        double id = c_id[i], tt = c_t[i];
        double v = c_yc[i] * (1.0 + std::fmod(id, 4.0));
        if (std::fmod(id + tt, 7.0) == 0.0) { v = 0.0; ++n_replaced; }
        cnt[static_cast<size_t>(i)] = v;
    }
    std::printf("  p7_count: rows meeting `mod(id+t,7)==0` = %lld (Stata: 685 real changes)\n",
                (long long)n_replaced);

    // Listwise deletion over (p7_count, x1, x2) — load_glm's rule.
    std::vector<double> y, x1, x2, yfrac;
    for (int64_t i = 0; i < nraw; ++i) {
        double cv = cnt[static_cast<size_t>(i)], a = c_x1[i], b = c_x2[i];
        if (std::isnan(cv) || std::isnan(a) || std::isnan(b)) continue;
        y.push_back(cv);
        x1.push_back(a);
        x2.push_back(b);
        yfrac.push_back(c_yf[i]);
    }
    const int64_t n = static_cast<int64_t>(y.size());
    int64_t nz = 0;
    for (double v : y) if (v == 0.0) ++nz;
    std::printf("  estimation sample: N=%lld  zero=%lld  nonzero=%lld\n",
                (long long)n, (long long)nz, (long long)(n - nz));
    chk_abs("N", static_cast<double>(n), 4671, 0);
    chk_abs("zero obs", static_cast<double>(nz), 667, 0);
    chk_abs("nonzero obs", static_cast<double>(n - nz), 4004, 0);

    const int k = 3;  // x1, x2, intercept — load_glm's [expanded x..., intercept] order
    std::vector<double> X(static_cast<size_t>(n) * k);
    for (int64_t i = 0; i < n; ++i) {
        X[i] = x1[static_cast<size_t>(i)];
        X[n + i] = x2[static_cast<size_t>(i)];
        X[2 * n + i] = 1.0;
    }

    // ---- 1. Gradient self-check FIRST -----------------------------------------
    // Analytic gradient vs a central difference of our own log-likelihood, at a
    // deliberately NON-optimal θ (a sign error is invisible at the optimum, where
    // both gradients are zero).
    auto grad_check = [&](const char* tag, bool nb, std::vector<double> theta) {
        const int np = static_cast<int>(theta.size());
        std::vector<double> g(static_cast<size_t>(np));
        zi::ll_grad(X.data(), n, k, y.data(), nb, theta, &g);
        for (int j = 0; j < np; ++j) {
            double h = 1e-6 * (std::fabs(theta[static_cast<size_t>(j)]) + 1.0);
            std::vector<double> tp = theta, tm = theta;
            tp[static_cast<size_t>(j)] += h;
            tm[static_cast<size_t>(j)] -= h;
            double lp = zi::ll_grad(X.data(), n, k, y.data(), nb, tp, nullptr);
            double lm = zi::ll_grad(X.data(), n, k, y.data(), nb, tm, nullptr);
            double num = (lp - lm) / (2 * h);
            double rel = std::fabs(g[static_cast<size_t>(j)] - num) /
                         (std::fabs(num) + 1e-8);
            std::printf("  %s d/dtheta[%d]: analytic=%-16.10g numeric=%-16.10g rel=%.2e\n",
                        tag, j, g[static_cast<size_t>(j)], num, rel);
            if (!(rel <= 1e-6)) {
                std::printf("    <<FAIL %s gradient component %d rel %.2e > 1e-6\n", tag, j, rel);
                fail = 1;
            }
        }
    };
    grad_check("zip ", false, {0.10, -0.05, 1.00, -1.50});
    grad_check("zinb", true, {0.10, -0.05, 1.00, -1.50, std::log(0.20)});

    // ---- 2. zip p7_count x1 x2, inflate(_cons) vce(robust) ---------------------
    ZiResult zp = zip_fit(X.data(), n, k, y.data());
    want_true("zip converged", zp.ok && zp.converged);
    std::printf("  zip iterations=%d\n", zp.iters);
    chk("zip ll_const", zp.ll_const, -10741.742, 1e-6);   // Stata's constant-only prefit
    chk("zip ll", zp.ll, -10579.278, 1e-6);
    chk("zip n_zero", static_cast<double>(zp.n_zero), 667, 0);
    chk("zip n_nonzero", static_cast<double>(zp.n_nonzero), 4004, 0);
    chk("zip b(x1)", zp.beta[0], .1747408, 1e-6);
    chk("zip b(x2)", zp.beta[1], .0584705, 1e-6);
    chk("zip b(_cons)", zp.beta[2], 1.337298, 1e-6);
    chk("zip b(inflate _cons)", zp.gamma0, -1.908065, 1e-6);
    // ML vce(robust) small-sample multiplier N/(N-1) — the P5-verified ML factor
    // (logit/probit/tobit/nbreg), NOT the regress-style N/(N-k) and not a bare
    // sandwich. The SE assertions below are what MEASURE that choice, and both
    // rivals were run to confirm they are rejected (seeded-RED, not assumed):
    //   q = 1              -> every SE off by 1.07e-4 relative (10x the tolerance)
    //   q = N/(N-np), np=4 -> every SE off by 3.21e-4 relative (32x the tolerance)
    // Only N/(N-1) lands inside 1e-5 on all nine pinned standard errors.
    const double q = static_cast<double>(n) / static_cast<double>(n - 1);
    std::vector<double> Vz = zi_robust_vcov(X.data(), n, k, y.data(), zp, q);
    want_true("zip robust V ok", !Vz.empty());
    auto se_of = [](const std::vector<double>& V, int np, int j) {
        return std::sqrt(std::max(0.0, V[static_cast<size_t>(j) * np + j]));
    };
    chk("zip se(x1)", se_of(Vz, zp.np, 0), .011351, 1e-5);
    chk("zip se(x2)", se_of(Vz, zp.np, 1), .0113554, 1e-5);
    chk("zip se(_cons)", se_of(Vz, zp.np, 2), .0123802, 1e-5);
    chk("zip se(inflate _cons)", se_of(Vz, zp.np, 3), .0463914, 1e-5);
    chk("zip z(x1)", zp.beta[0] / se_of(Vz, zp.np, 0), 15.39, 1e-3);
    double chi2_zip = 0;
    want_true("zip wald non-degenerate", zi::wald_chi2(Vz.data(), zp.np, zp.beta.data(), 2, chi2_zip));
    chk("zip Wald chi2(2)", chi2_zip, 274.94, 1e-4);

    // ---- 3. zinb p7_count x1 x2, inflate(_cons) vce(robust) --------------------
    ZiResult zb = zinb_fit(X.data(), n, k, y.data());
    want_true("zinb converged", zb.ok && zb.converged);
    std::printf("  zinb iterations=%d\n", zb.iters);
    chk("zinb ll_const", zb.ll_const, -10669.578, 1e-6);  // Stata's constant-only prefit
    chk("zinb ll", zb.ll, -10541.639, 1e-6);
    chk("zinb b(x1)", zb.beta[0], .1771959, 1e-6);
    chk("zinb b(x2)", zb.beta[1], .0607234, 1e-6);
    chk("zinb b(_cons)", zb.beta[2], 1.326524, 1e-6);
    chk("zinb b(inflate _cons)", zb.gamma0, -1.976382, 1e-6);
    chk("zinb lnalpha", zb.lnalpha, -2.867561, 1e-6);
    chk("zinb alpha", zb.alpha, .0568374, 1e-6);
    std::vector<double> Vb = zi_robust_vcov(X.data(), n, k, y.data(), zb, q);
    want_true("zinb robust V ok", !Vb.empty());
    chk("zinb se(x1)", se_of(Vb, zb.np, 0), .0114994, 1e-5);
    chk("zinb se(x2)", se_of(Vb, zb.np, 1), .0115312, 1e-5);
    chk("zinb se(_cons)", se_of(Vb, zb.np, 2), .0127821, 1e-5);
    chk("zinb se(inflate _cons)", se_of(Vb, zb.np, 3), .0502193, 1e-5);
    // The /lnalpha SE is the row that proves the sandwich covers the FULL θ: drop
    // the γ and lnα rows and every β SE above still matches, but this one is gone.
    double se_lna = se_of(Vb, zb.np, 4);
    chk("zinb se(/lnalpha)", se_lna, .1058344, 1e-5);
    chk("zinb se(alpha)", zb.alpha * se_lna, .0060153, 1e-5);
    const double z95 = 1.959963984540054;
    chk("zinb lnalpha ci_lo", zb.lnalpha - z95 * se_lna, -3.074993, 1e-6);
    chk("zinb lnalpha ci_hi", zb.lnalpha + z95 * se_lna, -2.66013, 1e-6);
    chk("zinb alpha ci_lo", std::exp(zb.lnalpha - z95 * se_lna), .04619, 1e-5);
    chk("zinb alpha ci_hi", std::exp(zb.lnalpha + z95 * se_lna), .0699391, 1e-5);
    double chi2_zinb = 0;
    want_true("zinb wald non-degenerate", zi::wald_chi2(Vb.data(), zb.np, zb.beta.data(), 2, chi2_zinb));
    chk("zinb Wald chi2(2)", chi2_zinb, 274.96, 1e-4);

    // ---- 4. fracreg logit yfrac x1 x2, vce(robust) -----------------------------
    // yfrac is EXACTLY inv-logit(.3*x1 - .2*x2 - .5), so the quasi-MLE recovers the
    // generating coefficients to machine precision and the robust meat collapses.
    for (double v : yfrac)
        if (!(v > 0.0 && v < 1.0)) { std::printf("  FAIL: yfrac outside (0,1)\n"); fail = 1; break; }
    LogitResult fr_ = logit_fit(X.data(), n, k, yfrac.data(), 100, 1e-14, nullptr);
    want_true("fracreg converged", fr_.converged);
    chk_abs("fracreg b(x1)", fr_.beta[0], .3, 1e-9);
    chk_abs("fracreg b(x2)", fr_.beta[1], -.2, 1e-9);
    chk_abs("fracreg b(_cons)", fr_.beta[2], -.5, 1e-9);
    double ll_f = frac::loglik(fr_.p.data(), yfrac.data(), n);
    double ll0_f = frac::null_loglik(yfrac.data(), n);
    chk("fracreg ll", ll_f, -3094.305, 1e-6);
    // Pseudo R² is printed to FOUR decimals in the Stata header (0.0129), so the
    // assertion is absolute at half of the last printed digit — a relative
    // tolerance here would only be pinning Stata's rounding.
    chk_abs("fracreg pseudo R2", 1.0 - ll_f / ll0_f, 0.0129, 5e-5);
    std::vector<double> ef(static_cast<size_t>(n));
    for (int64_t i = 0; i < n; ++i)
        ef[static_cast<size_t>(i)] = yfrac[static_cast<size_t>(i)] - fr_.p[static_cast<size_t>(i)];
    std::vector<double> Vf = logit_robust_vcov(X, n, k, ef, fr_.bread, q);
    // MAGNITUDE only (see the file header): Stata prints 1.23e-12 / 1.26e-12 / 1.13e-12.
    for (int j = 0; j < k; ++j) {
        double se = se_of(Vf, k, j);
        std::printf("  fracreg se[%d] = %.3e (Stata ~1.2e-12; magnitude assertion only)\n", j, se);
        if (!(se < 1e-10)) {
            std::printf("    <<FAIL fracreg se[%d] is not at machine-noise magnitude\n", j);
            fail = 1;
        }
    }
    double chi2_f = 0;
    bool ok_f = zi::wald_chi2(Vf.data(), k, fr_.beta.data(), 2, chi2_f);
    std::printf("  fracreg Wald: %s (Stata: chi2(0) = . , Prob = .)\n",
                ok_f ? "COMPUTED — degeneracy undetected" : "degenerate -> chi2 null, df 0");
    want_true("fracreg Wald reported missing", !ok_f);

    // ---- 5. The degeneracy rule must NOT fire on healthy fractional data --------
    // Same design, a genuinely dispersed fractional outcome: the model's own mean
    // blended 50/50 with a deterministic sawtooth in (0,1), so the residuals are
    // real and the robust V is a normal, well-conditioned matrix.
    std::vector<double> yh(static_cast<size_t>(n));
    for (int64_t i = 0; i < n; ++i) {
        double saw = 0.05 + 0.9 * static_cast<double>(i % 7) / 6.0;
        yh[static_cast<size_t>(i)] = 0.5 * yfrac[static_cast<size_t>(i)] + 0.5 * saw;
    }
    LogitResult hr = logit_fit(X.data(), n, k, yh.data(), 100, 1e-14, nullptr);
    want_true("healthy fracreg converged", hr.converged);
    std::vector<double> eh(static_cast<size_t>(n));
    for (int64_t i = 0; i < n; ++i)
        eh[static_cast<size_t>(i)] = yh[static_cast<size_t>(i)] - hr.p[static_cast<size_t>(i)];
    std::vector<double> Vh = logit_robust_vcov(X, n, k, eh, hr.bread, q);
    double chi2_h = 0;
    bool ok_h = zi::wald_chi2(Vh.data(), k, hr.beta.data(), 2, chi2_h);
    std::printf("  healthy: b=(%.6g, %.6g, %.6g) se(x1)=%.3e chi2=%.4f\n",
                hr.beta[0], hr.beta[1], hr.beta[2], se_of(Vh, k, 0), chi2_h);
    want_true("healthy Wald computed", ok_h && std::isfinite(chi2_h) && chi2_h > 0);
    want_true("healthy SEs are real", se_of(Vh, k, 0) > 1e-6);

    std::printf(fail ? "test_zicount: FAIL\n" : "test_zicount: OK\n");
    return fail;
}
