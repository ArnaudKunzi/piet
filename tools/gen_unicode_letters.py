#!/usr/bin/env python3
"""Regenerate src/core/unicode_letters.inc -- the code-point ranges of Unicode
category L (Lu Ll Lt Lm Lo) that src/core/ident.h uses to decide whether a
character may START a Stata name.

Stata 14+ (StataBE 19.5 probes, scratch-r150/uni-oracle rules*.do): a name
starts with an ASCII letter, `_`, or a Unicode letter; Lu/Ll/Lt/Lm/Lo starts are
accepted, Nd/No/Nl/Mn/Cf/Zs/Po/Sc/So starts are r(198).

Usage: tools/gatepy tools/gen_unicode_letters.py > src/core/unicode_letters.inc
(the repo interpreter; /usr/bin/python3 ships an older Unicode database)
"""
import sys
import unicodedata


def main() -> None:
    ranges = []
    lo = None
    for cp in range(0x80, 0x110000):
        is_letter = unicodedata.category(chr(cp)).startswith("L")
        if is_letter and lo is None:
            lo = cp
        elif not is_letter and lo is not None:
            ranges.append((lo, cp - 1))
            lo = None
    if lo is not None:
        ranges.append((lo, 0x10FFFF))
    out = sys.stdout
    out.write("// GENERATED by tools/gen_unicode_letters.py -- do not edit by hand.\n")
    out.write(f"// Unicode {unicodedata.unidata_version}, category L (Lu Ll Lt Lm Lo), code points >= 0x80.\n")
    out.write(f"// {len(ranges)} ranges.\n")
    for a, b in ranges:
        out.write(f"{{0x{a:X}, 0x{b:X}}},\n")


if __name__ == "__main__":
    main()
