#!/usr/bin/env python3
"""Regenerate src/core/ucase.inc -- the Unicode data behind PIET's header-name
case folding (`import delimited ..., case(lower|upper)`) and its name filter.

StataBE 19.5 (probes scratch-r150/uni-v/p1.do, p2.do) maps a header with the FULL
Unicode case mappings (ß -> SS, İ -> i + U+0307, ΐ -> three code points, final
sigma ας), keeps letters (category L) and decimal digits (Nd) and drops every
other non-ASCII character. This file carries, for code points >= 0x80:

  UCASE_LOWER / UCASE_UPPER   {cp, {out0, out1, out2}}   full mapping (0-padded)
  UCASE_CASED                 {lo, hi}                  "cased" (Lowercase|Uppercase|Lt)
  UCASE_IGNORABLE             {lo, hi}                  case-ignorable but not cased
  UCASE_DIGIT                 {lo, hi}                  category Nd

The final-sigma context test (U+03A3 -> U+03C2) uses CASED / IGNORABLE; StataBE
turns "ʰΣ" into "ʰς", i.e. a char that is both cased and case-ignorable counts as
cased, which is why IGNORABLE excludes CASED.

Usage: tools/gatepy tools/gen_unicode_case.py > src/core/ucase.inc
(the repo interpreter; /usr/bin/python3 ships an older Unicode database)
"""
import sys
import unicodedata


def ranges_of(pred):
    out = []
    lo = None
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(cp)
        if ok and lo is None:
            lo = cp
        elif not ok and lo is not None:
            out.append((lo, cp - 1))
            lo = None
    if lo is not None:
        out.append((lo, 0x10FFFF))
    return out


def is_cased(cp):
    c = chr(cp)
    return c.islower() or c.isupper() or unicodedata.category(c) == "Lt"


def is_ignorable_only(cp):
    if is_cased(cp):
        return False
    # "A" + c + SIGMA lowercases to a final sigma iff c is cased or case-ignorable.
    return ("A" + chr(cp) + "Σ").lower().endswith("ς")


def main() -> None:
    out = sys.stdout
    out.write("// GENERATED by tools/gen_unicode_case.py -- do not edit by hand.\n")
    out.write(f"// Unicode {unicodedata.unidata_version}. Included once per section with one of\n")
    out.write("// UCASE_LOWER, UCASE_UPPER, UCASE_CASED, UCASE_IGNORABLE, UCASE_DIGIT defined.\n")
    for name, fn in (("UCASE_LOWER", str.lower), ("UCASE_UPPER", str.upper)):
        out.write(("#if" if name == "UCASE_LOWER" else "#elif") + f" defined({name})\n")
        n = 0
        for cp in range(0x80, 0x110000):
            if 0xD800 <= cp <= 0xDFFF:
                continue
            c = chr(cp)
            m = fn(c)
            if m == c:
                continue
            assert len(m) <= 3, (hex(cp), m)
            cps = [ord(x) for x in m] + [0] * (3 - len(m))
            out.write("{0x%X, {0x%X, 0x%X, 0x%X}},\n" % (cp, cps[0], cps[1], cps[2]))
            n += 1
        out.write(f"// {n} entries\n")
    for name, pred in (
        ("UCASE_CASED", is_cased),
        ("UCASE_IGNORABLE", is_ignorable_only),
        ("UCASE_DIGIT", lambda cp: unicodedata.category(chr(cp)) == "Nd"),
    ):
        out.write(f"#elif defined({name})\n")
        rs = ranges_of(pred)
        for a, b in rs:
            out.write("{0x%X, 0x%X},\n" % (a, b))
        out.write(f"// {len(rs)} ranges\n")
    out.write("#endif\n")


if __name__ == "__main__":
    main()
